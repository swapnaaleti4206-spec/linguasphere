// Returns day of year (1-366)
export function getDayOfYear(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date - start + (start.getTimezoneOffset() - date.getTimezoneOffset()) * 60 * 1000;
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

// Get dynamic idiom and word for a given language & day offset
export function getDailyIdiomAndWord(language = 'english', dayOffset = 0) {
  const lang = (language || 'english').toLowerCase();
  const idioms = CLIENT_DAILY_IDIOMS[lang] || CLIENT_DAILY_IDIOMS.english;
  const words = CLIENT_DAILY_WORDS[lang] || CLIENT_DAILY_WORDS.english;

  const targetDate = new Date();
  targetDate.setDate(targetDate.getDate() + dayOffset);

  const dayOfYear = getDayOfYear(targetDate);
  const idiomIndex = Math.abs((dayOfYear + dayOffset * 3) % idioms.length);
  const wordIndex = Math.abs((dayOfYear + dayOffset * 5) % words.length);

  const dateOptions = { month: 'short', day: 'numeric', year: 'numeric' };
  const formattedDate = targetDate.toLocaleDateString(undefined, dateOptions);

  return {
    dateStr: formattedDate,
    dayOffset,
    idiom: idioms[idiomIndex],
    word: words[wordIndex],
    totalIdioms: idioms.length,
    totalWords: words.length
  };
}
